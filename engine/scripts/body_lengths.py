"""Back length and vertical trunk girth on 10 bodies, standing and in `hoods` (fit-engine-poc 4.4).

Run from engine/:  uv run python scripts/body_lengths.py
Writes docs/measurements/lengths-check.md (the table) and lengths-*.png (the paths drawn on two of
the bodies). Back length should be longer in `hoods` than standing: the spine flexes forward.
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from mpl_toolkits.mplot3d.art3d import Poly3DCollection  # noqa: E402

from simiq_fit.body import fit_body, load_model, pose_body  # noqa: E402
from simiq_fit.inputs import BodyInputs  # noqa: E402
from simiq_fit.landmarks import load_landmarks  # noqa: E402
from simiq_fit.measure import (  # noqa: E402
    back_length,
    back_length_path,
    vertical_trunk_arcs,
    vertical_trunk_girth,
)
from simiq_fit.poses import load_pose  # noqa: E402
from simiq_fit.tape import surface_arc  # noqa: E402

DOCS = Path(__file__).resolve().parents[1] / "docs" / "measurements"
BODIES = [  # sex, height cm, weight kg: across the supported ranges
    ("female", 158, 50),
    ("female", 165, 60),
    ("female", 170, 85),
    ("female", 175, 58),
    ("female", 182, 70),
    ("male", 168, 72),
    ("male", 175, 64),
    ("male", 178, 75),
    ("male", 185, 100),
    ("male", 195, 88),
]
DRAWN = ("female-165-60", "female-170-85", "male-185-100")


def draw(ax, vertices, faces, paths, azim, title):
    tri = vertices[faces]
    normals = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    normals /= np.maximum(np.linalg.norm(normals, axis=1, keepdims=True), 1e-12)
    a = np.radians(azim)
    colors = np.tile([0.8, 0.78, 0.75, 0.3], (len(faces), 1))
    colors[:, :3] *= (0.35 + 0.65 * np.abs(normals @ [np.cos(a), np.sin(a), 0.0]))[:, None]
    ax.add_collection3d(Poly3DCollection(tri, facecolors=colors, edgecolors="none"))
    for points, color in paths:
        ax.plot(points[:, 0], points[:, 1], points[:, 2], color=color, linewidth=2)
    center, half = vertices.mean(axis=0), np.ptp(vertices, axis=0).max() / 2
    for setter, c in zip((ax.set_xlim, ax.set_ylim, ax.set_zlim), center, strict=True):
        setter(c - half, c + half)
    ax.set_box_aspect((1, 1, 1))
    ax.view_init(elev=5, azim=azim)
    ax.set_axis_off()
    ax.set_title(title, fontsize=8)


def main():
    DOCS.mkdir(parents=True, exist_ok=True)
    model = load_model()
    faces = np.asarray(model.faces)
    landmarks = load_landmarks()["landmarks"]
    poses = {"standing": {}, "hoods": load_pose("hoods")}
    rows = [
        "# Back length and vertical trunk girth, standing and in `hoods`",
        "",
        "Generated by `scripts/body_lengths.py`. Lengths in cm along the skin.",
        "",
        "| Body | back standing | back hoods | change | trunk standing | trunk hoods | change |",
        "|---|---|---|---|---|---|---|",
    ]
    for sex, height, weight in BODIES:
        name = f"{sex}-{height}-{weight}"
        phenotype = fit_body(model, BodyInputs(sex=sex, height_cm=height, weight_kg=weight,
                                               body_type="regular"))  # fmt: skip
        posed = {p: pose_body(model, phenotype, r)["vertices"] for p, r in poses.items()}
        back = {p: 100 * back_length(v, faces, landmarks) for p, v in posed.items()}
        trunk = {p: 100 * vertical_trunk_girth(v, faces, landmarks) for p, v in posed.items()}
        rows.append(
            f"| {name} | {back['standing']:.1f} | {back['hoods']:.1f} | "
            f"{back['hoods'] - back['standing']:+.1f} | {trunk['standing']:.1f} | "
            f"{trunk['hoods']:.1f} | {trunk['hoods'] - trunk['standing']:+.1f} |"
        )
        print(rows[-1])
        if name in DRAWN:
            fig = plt.figure(figsize=(12, 6))
            for i, (pose, v) in enumerate(posed.items()):
                paths = [(surface_arc(v, faces, **back_length_path(v, landmarks)), "red")]
                paths += [(a, "blue") for a in vertical_trunk_arcs(v, faces, landmarks)]
                for j, azim in enumerate((0, 60)):
                    ax = fig.add_subplot(1, 4, 2 * i + j + 1, projection="3d")
                    draw(ax, v, faces, paths, azim, f"{pose}")
            fig.suptitle(f"{name}: back length (red), vertical trunk girth (blue)")
            fig.savefig(DOCS / f"lengths-{name}.png", dpi=120, bbox_inches="tight")
            plt.close(fig)
    (DOCS / "lengths-check.md").write_text("\n".join(rows) + "\n")
    print(f"wrote {DOCS}/lengths-check.md")


if __name__ == "__main__":
    main()
